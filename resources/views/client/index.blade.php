        // Generate Variant Options (if you have product variants)
        function generateVariantOptions(variants) {
            var html = '<div class="variant-options">';
            
            // Group variants by option name (e.g., Color, Size)
            var groupedVariants = {};
            variants.forEach(function(variant) {
                if (variant.options) {
                    variant.options.forEach(function(option) {
                        if (!groupedVariants[option.name]) {
                            groupedVariants[option.name] = [];
                        }
                        if (!groupedVariants[option.name].includes(option.value)) {
                            groupedVariants[option.name].push(option.value);
                        }
                    });
                }
            });
            
            // Generate select dropdowns for each option
            for (var optionName in groupedVariants) {
                html += '<div class="form-group">';
                html += '<label>' + optionName + ':</label>';
                html += '<select class="form-control variant-select" data-option="' + optionName + '">';
                groupedVariants[optionName].forEach(function(value) {
                    html += '<option value="' + value + '">' + value + '</option>';
                });
                html += '</select>';
                html += '</div>';
            }
            
            html += '</div>';
            return html;
        }

